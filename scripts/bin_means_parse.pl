#!/usr/bin/perl -CSD
# xi が書いた χ² のファイル（標準入力）から、選択関数つきの ξ_LS をビンでまとめた行を取り出し、
# 「量 R まとめ方 値 誤差」をタブで区切って書く（#18）。まとめ方は gls、plain（単純な平均）、ivar（分散の逆数の重み）。
# 例：「TRIAL の ξ_LS（footprint_50）：8.0–20.0 km の 2 ビンをまとめた値 0.118 ± 0.061」→ TRIAL 50 gls 0.118 0.061
use utf8;
my %method = ('をまとめた値' => 'gls', 'の単純な平均' => 'plain', 'の分散の逆数の重みの平均' => 'ivar');
while (<STDIN>) {
    if (/^(\w+) の ?(?:相互相関 )?ξ_LS（footprint_(\d+)）：.*?ビン(をまとめた値|の単純な平均|の分散の逆数の重みの平均) (-?[\d.]+) ± ([\d.]+)$/) {
        print join("\t", $1, $2, $method{$3}, $4, $5), "\n";
    }
}
